assert.equal(m.nodos[1].z,5800);
const plan=resolveDirection(r.model,'V1',[1,0],12000);applyMovement(r.model,plan);
assert(Math.abs((e.rasante[2].t-e.rasante[1].t)*12000-1500)<1e-8);
assert.equal(r.model.nodos[1].z,5840);
assert.throws(()=>insertLanding({...m,nodos:m.nodos.map(n=>({...n,cota_fija:true}))},'V1'),/fijada/);
