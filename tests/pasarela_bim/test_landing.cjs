const assert=require('node:assert/strict');
const {insertLanding,requiredLength,resolveDirection,applyMovement}=require('../../pasarela_bim/web/app.js');
const m={nodos:[{id:'A',x:0,y:0,z:5000},{id:'B',x:10000,y:0,z:5800},{id:'C',x:15000,y:0,z:6200}],tramos:[{id:'V1',desde:'A',hasta:'B',funcion:'rampa',ancho_mm:2000},{id:'V2',desde:'B',hasta:'C',funcion:'rampa'}],soportes:[],fundaciones:[]};
